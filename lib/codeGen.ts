// ============================================================
// AMA — Deterministic Code Scaffolding
// Generates the mechanical parts of the PLC project straight
// from the architecture data, so the AI agent only has to
// write logic bodies:
//   - SCL FUNCTION_BLOCK interface declarations (from variables)
//   - PLC tag table CSV (from I/O signals)
//   - HMI alarm list CSV (from alarms)
// ============================================================
import type { BlockBase, Variable } from '../types/machine';
import type { EntityDB } from './helpers';

/** Map an AMA variable to an SCL data type declaration. */
function sclTypeOf(v: Variable): string {
    switch (v.dataType) {
        case 'ARRAY OF':
            return v.customDataType || 'ARRAY[0..9] OF BOOL';
        case 'Union OF':
        case 'System':
        case 'Other':
            return v.customDataType || 'VARIANT';
        default:
            return v.dataType;
    }
}

function sanitizeIdentifier(name: string): string {
    return name.replace(/[^a-zA-Z0-9_]/g, '_');
}

const csvField = (v: any): string => `"${String(v ?? '').replace(/"/g, '""')}"`;

/**
 * Generate the SCL interface scaffold for one entity:
 * declarations are complete and compilable; the body is a TODO
 * left for the developer / Siemens Agent.
 */
export function generateSclInterface(entity: BlockBase, db: EntityDB): string {
    const bySection: Record<string, Variable[]> = { Input: [], Output: [], InOut: [], Local: [] };
    for (const v of entity.variables || []) {
        (bySection[v.scope] || bySection.Local).push(v);
    }

    const declare = (vars: Variable[]) =>
        vars.map(v => {
            const comment = v.description ? `   // ${v.description.replace(/\r?\n/g, ' ')}` : '';
            return `    ${sanitizeIdentifier(v.name)} : ${sclTypeOf(v)};${comment}`;
        }).join('\n');

    const lines: string[] = [];
    lines.push(`// ============================================================`);
    lines.push(`// ${entity.name} — [${entity.level}] ${entity.category}`);
    if (entity.description) lines.push(`// ${entity.description.replace(/\r?\n/g, ' ')}`);
    lines.push(`// Version: v${entity.currentVersion} · Automatically generated by AMA`);
    lines.push(`// Interface generated from the architecture data — DO NOT edit`);
    lines.push(`// the declarations by hand: update them in AMA and regenerate.`);
    lines.push(`// ============================================================`);

    // List assigned sub-modules so the agent knows what to instantiate
    const subRefs: { label: string; ids: string[] }[] = [
        { label: 'EM', ids: (entity as any).assignedEMs || [] },
        { label: 'CM', ids: (entity as any).assignedCMs || [] },
        { label: 'FB', ids: (entity as any).assignedFBs || [] },
    ];
    const subNames: string[] = [];
    for (const r of subRefs) {
        for (const refId of r.ids) {
            const sub = [...db.units, ...db.equipmentModules, ...db.controlModules, ...db.library]
                .find(e => e.id === refId);
            if (sub) subNames.push(`//   [${r.label}] ${sub.name}`);
        }
    }
    if (subNames.length > 0) {
        lines.push(`// Assigned modules (to instantiate in the logic):`);
        lines.push(...subNames);
        lines.push(`// ============================================================`);
    }

    lines.push(``);
    lines.push(`FUNCTION_BLOCK "${sanitizeIdentifier(entity.name)}"`);
    lines.push(`{ S7_Optimized_Access := 'TRUE' }`);
    lines.push(`VERSION : ${/^\d+\.\d+$/.test(entity.currentVersion) ? entity.currentVersion : '0.1'}`);
    lines.push(``);

    if (bySection.Input.length > 0) {
        lines.push(`VAR_INPUT`);
        lines.push(declare(bySection.Input));
        lines.push(`END_VAR`);
        lines.push(``);
    }
    if (bySection.Output.length > 0) {
        lines.push(`VAR_OUTPUT`);
        lines.push(declare(bySection.Output));
        lines.push(`END_VAR`);
        lines.push(``);
    }
    if (bySection.InOut.length > 0) {
        lines.push(`VAR_IN_OUT`);
        lines.push(declare(bySection.InOut));
        lines.push(`END_VAR`);
        lines.push(``);
    }
    if (bySection.Local.length > 0) {
        lines.push(`VAR`);
        lines.push(declare(bySection.Local));
        lines.push(`END_VAR`);
        lines.push(``);
    }

    lines.push(`BEGIN`);
    lines.push(`    // TODO: logic to implement (Siemens Agent / PLC developer)`);
    lines.push(`END_FUNCTION_BLOCK`);
    lines.push(``);

    return lines.join('\n');
}

/** PLC tag table (CSV) from the I/O signals of the given entities. */
export function generatePlcTagsCsv(entities: BlockBase[]): string {
    let out = 'Name,Data Type,Logical Address,Comment,Module\n';
    for (const e of entities) {
        for (const io of e.io || []) {
            const name = sanitizeIdentifier(io.variable || io.signalId || '');
            if (!name) continue;
            const addr = (io.address || '').trim();
            const logical = addr && !addr.startsWith('%') ? `%${addr}` : addr;
            const dataType = io.dataType === 'Other' || io.dataType === 'System'
                ? (io.customDataType || 'BOOL')
                : io.dataType;
            out += [csvField(name), csvField(dataType), csvField(logical), csvField(io.description), csvField(e.name)].join(',') + '\n';
        }
    }
    return out;
}

/** HMI alarm list (CSV) from the alarms of the given entities. */
export function generateHmiAlarmsCsv(entities: BlockBase[]): string {
    let out = 'AlarmID,Class,Message,TriggerVariable,Action,PossibleCauses,PossibleSolutions,Module\n';
    for (const e of entities) {
        for (const a of e.alarms || []) {
            out += [
                csvField(a.alarmId), csvField(a.level), csvField(a.message),
                csvField(a.triggerVariable), csvField(a.action),
                csvField(a.possibleCauses), csvField(a.possibleSolutions), csvField(e.name),
            ].join(',') + '\n';
        }
    }
    return out;
}

/** Procurement BOM (CSV) from the machine SBOM — the single source of truth. */
export function generateBomCsv(sbom: any[]): string {
    let out = 'InternalCode,SupplierCode,Description,Manufacturer,Type,Quantity,Unit,FWVersion,UsedIn,Notes';
    const sorted = [...sbom].sort((a, b) =>
        `${a.type || 'Hardware'}${a.supplierCode || a.hardware || ''}`.localeCompare(`${b.type || 'Hardware'}${b.supplierCode || b.hardware || ''}`));
    for (const r of sorted) {
        const supplierCode = r.supplierCode || (String(r.hardware || '').match(/\(([^)]+)\)/) || [])[1] || '';
        out += [
            csvField(r.internalCode || ''), csvField(supplierCode), csvField(r.hardware || ''), csvField(r.manufacturer || ''),
            csvField(r.type || 'Hardware'), r.quantity || 1, csvField(r.unit || 'pz'), csvField(r.firmware || ''),
            csvField(r.sourceEntity || 'Machine'), csvField(r.notes || ''),
        ].join(',') + '\n';
    }
    return out;
}

/**
 * Build the `generated/` portion of the Git export: SCL scaffolds for every
 * entity that has no hand-written code yet, plus machine-wide tag and alarm
 * tables. Entities that already have code keep it (exported elsewhere as .scl).
 */
export function buildGeneratedFiles(entities: BlockBase[], db: EntityDB): { [path: string]: string } {
    const files: { [path: string]: string } = {};
    const usedNames = new Map<string, number>();

    for (const e of entities) {
        if ((e.code || '').trim().length > 0) continue;       // hand-written code wins
        if ((e.variables || []).length === 0) continue;       // nothing to declare
        let name = sanitizeIdentifier(e.name);
        const n = usedNames.get(name) || 0;
        usedNames.set(name, n + 1);
        if (n > 0) name = `${name}_${n + 1}`;
        files[`generated/scl/${name}.scl`] = generateSclInterface(e, db);
    }

    files['generated/plc_tags.csv'] = generatePlcTagsCsv(entities);
    files['generated/hmi_alarms.csv'] = generateHmiAlarmsCsv(entities);
    files['generated/README.md'] = [
        `# Automatically Generated Files`,
        ``,
        `Content generated deterministically from the AMA architecture data:`,
        ``,
        `- \`scl/*.scl\` — FUNCTION_BLOCK interfaces (complete declarations, TODO body)`,
        `  for assembled entities that have no hand-written code yet.`,
        `- \`plc_tags.csv\` — table of PLC variables mapped to the physical I/O.`,
        `- \`hmi_alarms.csv\` — alarm list for the HMI.`,
        ``,
        `The Siemens Agent only has to implement the logic bodies:`,
        `the interfaces, tags and alarms are already defined here and MUST NOT be reinvented.`,
        ``,
    ].join('\n');

    return files;
}
